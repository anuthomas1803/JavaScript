//FUNCTIONS
//function with name : Simple function
function add(a,b)
{
    return a+b;
}
let sum=add(2,3);
console.log(sum);

//anonymous methods : method has no name
let sumofintegers=function(c,d)
{
    return c+d;
}
console.log(sumofintegers(2,3));

//using arrow funtion
let sumofnumbers=(c,d)=>c+d;
console.log(sumofnumbers(2,3));


